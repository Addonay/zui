//! Raster image decode via vendored stb_image (public domain).
//!
//! Cold path only: decode allocates (stb malloc + one allocator copy) and
//! must never run per frame — results live in the image cache (`cache.zig`)
//! and frames reference pool offsets.

const std = @import("std");
const builtin = @import("builtin");
const c = @import("c.zig");
const limits = @import("../core/limits.zig");
const zlog = @import("../core/log.zig");

pub const Format = enum {
    png,
    jpeg,
    gif,
    bmp,
    svg,
    unknown,

    pub fn isRaster(self: Format) bool {
        return switch (self) {
            .png, .jpeg, .gif, .bmp => true,
            .svg, .unknown => false,
        };
    }
};

/// Magic-byte sniff. SVG is XML text: skip leading whitespace/BOM and look
/// for `<svg`, `<?xml`, or `<!DOCTYPE svg`.
pub fn sniff(bytes: []const u8) Format {
    if (bytes.len >= 8 and std.mem.eql(u8, bytes[0..8], "\x89PNG\r\n\x1a\n")) return .png;
    if (bytes.len >= 3 and bytes[0] == 0xFF and bytes[1] == 0xD8 and bytes[2] == 0xFF) return .jpeg;
    if (bytes.len >= 6 and (std.mem.eql(u8, bytes[0..6], "GIF87a") or std.mem.eql(u8, bytes[0..6], "GIF89a"))) return .gif;
    if (bytes.len >= 2 and bytes[0] == 'B' and bytes[1] == 'M') return .bmp;
    if (isSvgText(bytes)) return .svg;
    return .unknown;
}

fn isSvgText(bytes: []const u8) bool {
    var i: usize = 0;
    // UTF-8 BOM.
    if (bytes.len >= 3 and bytes[0] == 0xEF and bytes[1] == 0xBB and bytes[2] == 0xBF) i = 3;
    while (i < bytes.len and (bytes[i] == ' ' or bytes[i] == '\t' or bytes[i] == '\n' or bytes[i] == '\r')) : (i += 1) {}
    const rest = bytes[@min(i, bytes.len)..];
    // Case-insensitive `<svg` check without allocating.
    if (rest.len >= 4 and rest[0] == '<') {
        const tag = rest[1..@min(rest.len, 8)];
        if (startsWithIgnoreCase(tag, "svg")) return true;
        if (startsWithIgnoreCase(tag, "?xml")) return true;
        if (rest.len >= 9 and startsWithIgnoreCase(rest[1..9], "!doctype")) return true;
    }
    return false;
}

fn startsWithIgnoreCase(haystack: []const u8, needle: []const u8) bool {
    if (haystack.len < needle.len) return false;
    for (needle, 0..) |nc, k| {
        var hc = haystack[k];
        if (hc >= 'A' and hc <= 'Z') hc += 'a' - 'A';
        var lc = nc;
        if (lc >= 'A' and lc <= 'Z') lc += 'a' - 'A';
        if (hc != lc) return false;
    }
    return true;
}

pub const Decoded = struct {
    pixels: []u8, // allocator-owned RGBA8
    w: u32,
    h: u32,

    pub const empty: Decoded = .{ .pixels = &.{}, .w = 0, .h = 0 };
};

pub const DecodeError = error{
    UnsupportedFormat,
    DecodeFailed,
    TooLarge,
    OutOfMemory,
};

/// Header-only probe: dimensions without decoding pixels.
pub fn probe(bytes: []const u8) DecodeError!struct { w: u32, h: u32, format: Format } {
    const fmt = sniff(bytes);
    if (!fmt.isRaster()) return DecodeError.UnsupportedFormat;
    if (bytes.len > std.math.maxInt(c_int)) return DecodeError.TooLarge;
    var w: c_int = 0;
    var h: c_int = 0;
    var comp: c_int = 0;
    if (c.api.stbiInfo(bytes.ptr, @intCast(bytes.len), &w, &h, &comp) == 0) {
        zlog.log("images", "probe failed: {s}", .{std.mem.span(c.api.stbiFailure())});
        return DecodeError.DecodeFailed;
    }
    if (w <= 0 or h <= 0) return DecodeError.DecodeFailed;
    if (@as(u64, @intCast(w)) * @as(u64, @intCast(h)) > limits.MAX_IMAGE_PIXELS) return DecodeError.TooLarge;
    return .{ .w = @intCast(w), .h = @intCast(h), .format = fmt };
}

/// Full decode to allocator-owned RGBA8. Rejects oversize images before
/// (and after) decode; copies out of stb's malloc so ownership is uniform.
pub fn decode(allocator: std.mem.Allocator, bytes: []const u8) DecodeError!Decoded {
    const fmt = sniff(bytes);
    if (!fmt.isRaster()) return DecodeError.UnsupportedFormat;
    if (bytes.len == 0 or bytes.len > std.math.maxInt(c_int)) return DecodeError.TooLarge;
    var w: c_int = 0;
    var h: c_int = 0;
    var comp: c_int = 0;
    const raw = c.api.stbiLoad(bytes.ptr, @intCast(bytes.len), &w, &h, &comp, 4) orelse {
        zlog.log("images", "stb decode failed: {s}", .{std.mem.span(c.api.stbiFailure())});
        return DecodeError.DecodeFailed;
    };
    defer c.api.stbiFree(raw);
    if (w <= 0 or h <= 0) return DecodeError.DecodeFailed;
    const uw: u64 = @intCast(w);
    const uh: u64 = @intCast(h);
    if (uw > limits.MAX_IMAGE_DIMENSION or uh > limits.MAX_IMAGE_DIMENSION) return DecodeError.TooLarge;
    if (uw * uh > limits.MAX_IMAGE_PIXELS) return DecodeError.TooLarge;
    const n = uw * uh * 4;
    const out = allocator.alloc(u8, n) catch return DecodeError.OutOfMemory;
    @memcpy(out, raw[0..n]);
    return .{ .pixels = out, .w = @intCast(w), .h = @intCast(h) };
}

test "sniff identifies raster magics and svg text" {
    try std.testing.expectEqual(Format.png, sniff("\x89PNG\r\n\x1a\nrest"));
    try std.testing.expectEqual(Format.jpeg, sniff("\xFF\xD8\xFF\xE0rest"));
    try std.testing.expectEqual(Format.gif, sniff("GIF89a..."));
    try std.testing.expectEqual(Format.bmp, sniff("BM...."));
    try std.testing.expectEqual(Format.svg, sniff("<svg xmlns=\"x\">"));
    try std.testing.expectEqual(Format.svg, sniff("  \n <?xml version=\"1.0\"?>"));
    try std.testing.expectEqual(Format.svg, sniff("\xEF\xBB\xBF<svg>"));
    try std.testing.expectEqual(Format.svg, sniff("<SVG width=\"1\">"));
    try std.testing.expectEqual(Format.unknown, sniff("hello"));
    try std.testing.expectEqual(Format.unknown, sniff(&.{}));

    // Bounds: probe rejects empty/oversize without touching stb.
    try std.testing.expectError(DecodeError.UnsupportedFormat, probe("<svg/>"));
    try std.testing.expectError(DecodeError.UnsupportedFormat, probe(&.{}));
}

