test "stb decodes png to exact pixels" {
    const t = std.testing.allocator;
    const p = try probe(red_png);
    try std.testing.expectEqual(@as(u32, 1), p.w);
    try std.testing.expectEqual(Format.png, p.format);
    const d = try decode(t, red_png);
    defer t.free(d.pixels);
    try std.testing.expectEqual(@as(u32, 1), d.w);
    try std.testing.expectEqual(@as(u32, 1), d.h);
    try std.testing.expectEqualSlices(u8, &.{ 255, 0, 0, 255 }, d.pixels);

    const g = try decode(t, gradient_png);
    defer t.free(g.pixels);
    try std.testing.expectEqual(@as(u32, 2), g.w);
    try std.testing.expectEqual(@as(u32, 2), g.h);
    // Row-major RGB(A): red, green / blue, white.
    try std.testing.expectEqual(@as(u8, 255), g.pixels[0]);
    try std.testing.expectEqual(@as(u8, 255), g.pixels[5]);
    try std.testing.expectEqual(@as(u8, 255), g.pixels[10]);
    try std.testing.expectEqual(@as(u8, 255), g.pixels[12]);
    try std.testing.expectEqual(@as(u8, 255), g.pixels[15]);
}

