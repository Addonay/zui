/// The Zig face of upstream's `GradientLutExt` trait: the element type
/// selects the conversion.
pub fn GradientLutExt(comptime T: type) type {
    if (T != u8 and T != f32) {
        @compileError("GradientLut only supports u8 and f32, got " ++ @typeName(T));
    }
    return struct {
        /// The zero value (upstream `ZERO`).
        pub const ZERO: T = switch (T) {
            u8 => 0,
            f32 => 0.0,
            else => unreachable,
        };

        /// Convert from `f32x16` to `[T; 16]`.
        pub fn fromF32x16(color: F32x16) [16]T {
            return switch (T) {
                // `f32_to_u8(color * 255.0 + 0.5)`, with upstream's
                // non-FMA `mul_add` on the portable/baseline backends.
                u8 => util.f32ToU8(simd.mulAddUnfused(
                    color,
                    @as(F32x16, @splat(255.0)),
                    @as(F32x16, @splat(0.5)),
                )),
                f32 => color,
                else => unreachable,
            };
        }
    };
}

/// A lookup table for sampled gradient values.
pub fn GradientLut(comptime T: type) type {
    return struct {
        values: [][4]T,
        scale: f32,

        const Self = @This();
        const Ext = GradientLutExt(T);

        /// Create a new lookup table (upstream `new`).
        ///
        /// Upstream vectorizes the constructor through `simd.vectorize`; the
        /// port always runs the SIMD-width loop (the helpers in
        /// `src/simd/root.zig` lower to scalar code on fallback targets).
        pub fn init(allocator: std.mem.Allocator, ranges: []const GradientRange) std.mem.Allocator.Error!Self {
            const lut_size = determineLutSize(ranges);
            const values = try allocator.alloc([4]T, lut_size);
            errdefer allocator.free(values);

            const zero: [4]T = .{ Ext.ZERO, Ext.ZERO, Ext.ZERO, Ext.ZERO };
            @memset(values, zero);

            // Flat view of the LUT, matching upstream's
            // `bytemuck::cast_slice_mut::<[T; 4], T>`.
            const lut_flat: []T = @as([*]T, @ptrCast(values.ptr))[0 .. lut_size * 4];

            // Calculate how many indices are covered by each range.
            const scale: f32 = @as(f32, @floatFromInt(lut_size)) - 1.0;
            const inv_lut_scale: F32x4 = @splat(1.0 / scale);
            const add_factor: F32x4 = @as(F32x4, .{ 0.0, 1.0, 2.0, 3.0 }) * inv_lut_scale;

            var prev_idx: usize = 0;
            for (ranges) |range| {
                const max_idx: usize = @intFromFloat(
                    range.x1 * @as(f32, @floatFromInt(lut_size)),
                );

                const bias4 = simd.fromSlice(F32x4, &range.bias);
                const scale4 = simd.fromSlice(F32x4, &range.scale);
                const biases = simd.blockSplat(bias4, bias4, bias4, bias4);
                const scales = simd.blockSplat(scale4, scale4, scale4, scale4);

                var idx = prev_idx;
                while (idx < max_idx) : (idx += 4) {
                    const t_vals_4 = simd.mulAddUnfused(
                        @as(F32x4, @splat(@as(f32, @floatFromInt(idx)))),
                        inv_lut_scale,
                        add_factor,
                    );
                    const t_vals = simd.elementWiseSplat(t_vals_4);

                    var result = simd.mulAddUnfused(scales, t_vals, biases);
                    const alphas = simd.splat4thPerGroup(result);
                    // Premultiply colors, since interpolation happened in
                    // unpremultiplied space.
                    if (range.interpolation_alpha_space == .unpremultiplied) {
                        const color_lane_mask: simd.Mask(F32x16) = .{
                            true, true, true, false,
                            true, true, true, false,
                            true, true, true, false,
                            true, true, true, false,
                        };
                        result = simd.select(F32x16, color_lane_mask, result * alphas, alphas);
                    }

                    // Floating-point impreciseness can push values above 1 or
                    // RGB above alpha; clamp to prevent later overflow.
                    result = @min(@min(result, @as(F32x16, @splat(1.0))), alphas);
                    const rs = Ext.fromF32x16(result);

                    // We always compute 4 samples at a time, but a ramp does
                    // not necessarily start at a multiple of 4, so truncate.
                    const start = idx * 4;
                    const end = @min(idx + 4, lut_size) * 4;
                    @memcpy(lut_flat[start..end], rs[0 .. end - start]);
                }
                prev_idx = max_idx;
            }

            return .{ .values = values, .scale = scale };
        }

        /// Release the lookup table.
        pub fn deinit(self: *Self, allocator: std.mem.Allocator) void {
            allocator.free(self.values);
            self.* = undefined;
        }

        /// Get the sample value at a specific index.
        pub fn get(self: *const Self, idx: usize) [4]T {
            return self.values[idx];
        }

        /// Return the raw array of gradient sample values.
        pub fn lut(self: *const Self) []const [4]T {
            return self.values;
        }

        /// Return the number of entries in the lookup table.
        pub fn width(self: *const Self) usize {
            return self.values.len;
        }

        /// Get the scale factor by which to scale the parametric value to
        /// compute the correct lookup index.
        pub fn scaleFactor(self: *const Self) f32 {
            return self.scale;
        }
    };
}

/// Determine the lookup table size for a set of ranges.
///
/// Inspired by Blend2D: 256 entries for one range, 512 for two, 1024 for more.
/// Tiny offsets increase the resolution, clamped to `MAX_GRADIENT_LUT_SIZE`.
fn determineLutSize(ranges: []const GradientRange) usize {
    const stop_len: usize = switch (ranges.len) {
        1 => 256,
        2 => 512,
        else => 1024,
    };

    var last_x1: f32 = 0.0;
    var min_size: usize = 0;

    for (ranges) |range| {
        const x1 = range.x1;
        // For example, if the first stop is at 0.001, we need a resolution of
        // at least 1000 to safely capture it.
        const res = @min(ceilToUsizeSat(1.0 / (x1 - last_x1)), MAX_GRADIENT_LUT_SIZE);
        const next_pow2: usize = if (res == 0) 1 else std.math.ceilPowerOfTwoAssert(usize, res);
        min_size = @max(min_size, next_pow2);
        last_x1 = x1;
    }

    // Take the maximum of both, but don't exceed the maximum size.
    return @max(stop_len, min_size);
}

/// Rust's `f32 as usize` saturating cast of an already-ceiled value, with the
/// `MAX_GRADIENT_LUT_SIZE` clamp applied. The clamp is equivalent to
/// upstream's trailing `.min(MAX_GRADIENT_LUT_SIZE)` because the following
/// `next_power_of_two` cannot leave the clamped range (4096 is a power of two).
fn ceilToUsizeSat(value: f32) usize {
    const ceiled = @ceil(value);
    if (std.math.isNan(ceiled) or ceiled <= 0.0) return 0;
    if (ceiled >= @as(f32, @floatFromInt(MAX_GRADIENT_LUT_SIZE))) {
        return MAX_GRADIENT_LUT_SIZE;
    }
    return @intFromFloat(ceiled);
}

