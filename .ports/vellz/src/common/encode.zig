//! Port of vello_common encode.rs (Apache-2.0 OR MIT).
//!
//! Paint encoding for the sparse-strip renderer: `EncodedPaint` (gradient,
//! image, blurred rounded rectangle) plus the gradient range/LUT machinery the
//! fine rasterizer samples from.
//!
//! Scope decisions (numbered as in the port task; every divergence from the
//! upstream file is called out here):
//!
//! 1. **sRGB-only stops.** `ColorStop.color` is `AlphaColor(Srgb)` in this
//!    port, so the sRGB branch of upstream `encode_stops` is transcribed
//!    directly: each adjacent stop pair becomes one `GradientRange` with
//!    `bias + x * scale` interpolation. Upstream's `color::gradient` /
//!    `gradient_unpremultiplied` expansion (which subdivides the range with
//!    extra interpolated stops for other color spaces) is not ported; a
//!    gradient whose `interpolation_cs` is not sRGB returns
//!    `error.Unsupported` instead of silently approximating with sRGB.
//!    `GradientCacheKey` still carries `stops`, `interpolation_cs`, and
//!    `hue_direction` for structural fidelity.
//!    `InterpolationAlphaSpace` is handled exactly as upstream: premultiplied
//!    ranges store premultiplied colors; unpremultiplied ranges store straight
//!    colors and the LUT premultiplies them at generation time.
//! 2. **Validation matches upstream.** Empty stops produce a black solid
//!    paint, one stop produces that stop's color, and invalid offsets/kinds
//!    produce the first stop's color (upstream returns these fallbacks rather
//!    than panicking). Offsets must be in `[0, 1]` (NaN is invalid) and
//!    non-decreasing; missing first/last offsets are padded to 0/1 with copies
//!    of the first/last stop. Degenerate linear gradients use
//!    `DEGENERATE_THRESHOLD = 1e-6`; radial validates negative radii and
//!    coincident center/radius pairs; sweep requires
//!    `end_angle > start_angle` and a delta larger than the threshold.
//!    `NUDGE_VAL = 1e-7` guards the range divisor.
//! 3. **Radial gradients** (the Skia conical algorithm) are ported including
//!    `FocalData` (`create`/`is_focal_on_circle`/`is_swapped`/
//!    `is_well_behaved`/`is_natively_focal`) and `RadialKind::has_undefined`.
//! 4. **Gradient LUTs** exist for both `u8` and `f32`, generated by the same
//!    vector math as upstream through the ported `src/simd/root.zig` helpers:
//!    `elementWiseSplat`, `splat4thPerGroup`, `blockSplat`, and
//!    `simd.mulAddUnfused`. Fused multiply-add would not match upstream's
//!    portable/baseline backends, matching the convention set by
//!    `common/strip.zig`. `GradientLutExt` is a namespace (Zig has no traits)
//!    selected by the `T` parameter.
//! 5. **Lazy LUT storage.** Upstream uses `OnceCell` (single-threaded) or
//!    `OnceLock` (multithreading); this port stores `?GradientLut` and
//!    initializes on first `u8Lut`/`f32Lut` access. Those accessors take
//!    `*EncodedGradient` and mutate through the pointer, so they are
//!    single-threaded for now; M4 adds synchronization. Allocation failure
//!    propagates (`error.OutOfMemory`) and leaves the cell empty.
//! 6. **Images**: `EncodedImage` keeps upstream's fields and computes the same
//!    inverse transform, x/y advances, and transparency flag. `sampler.alpha`
//!    is folded into the tint color's alpha (creating a white multiply tint
//!    when there is none) and clamped to 1, and `ImageQuality.medium` is
//!    downgraded to `.low` for integer-only translations.
//! 7. **Blurred rounded rectangles**: `EncodedBlurredRoundedRectangle` is
//!    declared with upstream's fields but its encoder returns
//!    `error.Unsupported`; the algorithm belongs to the filters/BRR work
//!    (M2-later) and no field is faked.
//! 8. `EncodedPaint.mayHaveTransparency` and the `Paint`-level query are
//!    ported; the transparent-source path works for images whose pixels are
//!    resolved later through `NoOpImageResolver`, because the flag comes from
//!    the `ImageSource` transparency hint or a translucent tint.
//!
//! Ownership/allocator note: `EncodeExt` equivalents take an explicit
//! allocator. `EncodedGradient` owns its `ranges` slice and the cloned stops
//! in `cache_key`; `EncodedImage` owns one `ImageSource` reference.
//! `deinit(allocator)` releases exactly those resources, and
//! `Paint`/`IndexedPaint` values pushed into `paints` are owned by the caller.
//! `GradientLut(T)` owns its lookup table. Nothing is freed implicitly.

