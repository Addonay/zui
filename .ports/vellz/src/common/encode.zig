test "determine_lut_size stop counts, gaps, and cap" {
    const one = [_]GradientRange{syntheticRange(1.0)};
    try testing.expectEqual(@as(usize, 256), determineLutSize(&one));

    const two = [_]GradientRange{ syntheticRange(0.5), syntheticRange(1.0) };
    try testing.expectEqual(@as(usize, 512), determineLutSize(&two));

    const three = [_]GradientRange{ syntheticRange(0.25), syntheticRange(0.5), syntheticRange(1.0) };
    try testing.expectEqual(@as(usize, 1024), determineLutSize(&three));

    // A tiny first gap raises the resolution beyond the stop-count default.
    const tiny_gap = [_]GradientRange{ syntheticRange(0.001), syntheticRange(1.0) };
    try testing.expectEqual(@as(usize, 1024), determineLutSize(&tiny_gap));

    // 1 / 4096 is exactly representable; one more octave is capped at 4096.
    const exact_pow2 = [_]GradientRange{ syntheticRange(1.0 / 4096.0), syntheticRange(1.0) };
    try testing.expectEqual(@as(usize, 4096), determineLutSize(&exact_pow2));

    const tiny = [_]GradientRange{ syntheticRange(0.0001), syntheticRange(1.0) };
    try testing.expectEqual(@as(usize, MAX_GRADIENT_LUT_SIZE), determineLutSize(&tiny));

    // Duplicate offsets make the divisor zero (infinite resolution), capped.
    const duplicate = [_]GradientRange{ syntheticRange(0.5), syntheticRange(0.5), syntheticRange(1.0) };
    try testing.expectEqual(@as(usize, MAX_GRADIENT_LUT_SIZE), determineLutSize(&duplicate));
}

fn syntheticRange(x1: f32) GradientRange {
    return .{
        .x1 = x1,
        .bias = .{ 0.0, 0.0, 0.0, 0.0 },
        .scale = .{ 0.0, 0.0, 0.0, 0.0 },
        .interpolation_alpha_space = .premultiplied,
    };
}

/// The x86 `cvttps2dq`-then-low-byte conversion `util.f32ToU8` documents,
/// written out so the reference LUT does not call the implementation.
fn referenceConvertU8(x: f32) u8 {
    if (std.math.isNan(x)) return 0;
    const truncated = @trunc(x);
    if (truncated >= 2147483648.0 or truncated < -2147483648.0) return 0;
    const as_i32: i32 = @intFromFloat(truncated);
    return @truncate(@as(u32, @bitCast(as_i32)));
}

/// Independent scalar transcription of the documented LUT math:
/// `bias + x * scale` with upstream's unfused `mul_add`, the
/// unpremultiplied fixup, and `min(1.0).min(alpha)` clamping.
fn referenceLut(
    comptime T: type,
    allocator: std.mem.Allocator,
    ranges: []const GradientRange,
) ![]T {
    const lut_size = determineLutSize(ranges);
    const out = try allocator.alloc(T, lut_size * 4);
    errdefer allocator.free(out);

    const scale: f32 = @as(f32, @floatFromInt(lut_size)) - 1.0;
    const inv_lut_scale: f32 = 1.0 / scale;

    var prev_idx: usize = 0;
    for (ranges) |range| {
        const max_idx: usize = @intFromFloat(range.x1 * @as(f32, @floatFromInt(lut_size)));
        var idx = prev_idx;
        while (idx < max_idx) : (idx += 4) {
            const base_t = @as(f32, @floatFromInt(idx)) * inv_lut_scale;
            var block: [16]T = undefined;
            // The last block of a table can be truncated; only the copied
            // lanes are part of the reference.
            const lanes_in_block = @min(idx + 4, lut_size) - idx;
            for (0..lanes_in_block) |lane| {
                const t = base_t + @as(f32, @floatFromInt(lane)) * inv_lut_scale;
                var pixel: [4]f32 = undefined;
                for (0..4) |channel| {
                    pixel[channel] = range.scale[channel] * t + range.bias[channel];
                }
                const alpha = pixel[3];
                if (range.interpolation_alpha_space == .unpremultiplied) {
                    pixel[0] = pixel[0] * alpha;
                    pixel[1] = pixel[1] * alpha;
                    pixel[2] = pixel[2] * alpha;
                }
                for (0..4) |channel| {
                    const clamped = @min(@min(pixel[channel], 1.0), alpha);
                    block[lane * 4 + channel] = if (T == u8)
                        referenceConvertU8(clamped * 255.0 + 0.5)
                    else
                        clamped;
                }
            }
            const start = idx * 4;
            const end = @min(idx + 4, lut_size) * 4;
            @memcpy(out[start..end], block[0 .. end - start]);
        }
        prev_idx = max_idx;
    }

    return out;
}

test "LUT bytes match an independent scalar computation" {
    const allocator = testing.allocator;
    var paints: std.ArrayList(EncodedPaint) = .empty;
    defer drainPaints(&paints, allocator);

    const opaque_stops = [_]ColorStop{
        ColorStop.init(0.0, peniko.palette.css.RED),
        ColorStop.init(0.5, peniko.palette.css.GREEN),
        ColorStop.init(1.0, peniko.palette.css.BLUE),
    };
    const translucent_stops = [_]ColorStop{
        ColorStop.init(0.0, Color.new(.{ 1.0, 0.0, 0.0, 0.25 })),
        ColorStop.init(0.1, Color.new(.{ 0.0, 1.0, 0.0, 0.5 })),
        ColorStop.init(1.0, Color.new(.{ 0.0, 0.0, 1.0, 1.0 })),
    };
    const padded_stops = [_]ColorStop{
        ColorStop.init(0.25, peniko.palette.css.RED),
        ColorStop.init(0.75, Color.new(.{ 0.0, 0.0, 1.0, 0.5 })),
    };
    const tiny_gap_stops = [_]ColorStop{
        ColorStop.init(0.0, peniko.palette.css.RED),
        ColorStop.init(0.001, Color.new(.{ 0.0, 1.0, 0.0, 0.5 })),
        ColorStop.init(1.0, peniko.palette.css.BLUE),
    };

    // (stops, alpha space) pairs; stop slices must outlive the loop.
    const cases = [_]struct { stops: []const ColorStop, alpha_space: InterpolationAlphaSpace }{
        .{ .stops = &opaque_stops, .alpha_space = .premultiplied },
        .{ .stops = &translucent_stops, .alpha_space = .premultiplied },
        .{ .stops = &translucent_stops, .alpha_space = .unpremultiplied },
        .{ .stops = &padded_stops, .alpha_space = .premultiplied },
        .{ .stops = &tiny_gap_stops, .alpha_space = .premultiplied },
    };

    for (cases) |case| {
        var gradient = try makeGradient(
            allocator,
            .{ .linear = peniko.LinearGradientPosition.new(Point.new(0.0, 0.0), Point.new(10.0, 0.0)) },
            case.stops,
        );
        defer gradient.deinit();
        gradient = gradient.withInterpolationAlphaSpace(case.alpha_space);

        const paint = try encodeGradient(&gradient, allocator, &paints, Affine.IDENTITY, null);
        const encoded = encodedGradientOf(&paints, paint);

        const u8_lut = try encoded.u8Lut(allocator);
        const expected_u8 = try referenceLut(u8, allocator, encoded.ranges);
        defer allocator.free(expected_u8);
        try testing.expectEqual(expected_u8.len, u8_lut.width() * 4);
        try testing.expectEqualSlices(u8, expected_u8, std.mem.sliceAsBytes(u8_lut.lut()));
        try testing.expectEqual(
            @as(f32, @floatFromInt(u8_lut.width())) - 1.0,
            u8_lut.scaleFactor(),
        );

        const f32_lut = try encoded.f32Lut(allocator);
        const expected_f32 = try referenceLut(f32, allocator, encoded.ranges);
        defer allocator.free(expected_f32);
        try testing.expectEqual(expected_f32.len, f32_lut.width() * 4);
        try testing.expectEqualSlices(
            f32,
            expected_f32,
            std.mem.bytesAsSlice(f32, std.mem.sliceAsBytes(f32_lut.lut())),
        );

        // The LUT is built once and reused.
        try testing.expectEqual(u8_lut, try encoded.u8Lut(allocator));
    }
}

test "u8 lut clamps min(1.0).min(alpha)" {
    const allocator = testing.allocator;
    // bias RGB deliberately exceeds 1 and exceeds alpha; scale is zero so
    // every index has the same value.
    const ranges = [_]GradientRange{.{
        .x1 = 1.0,
        .bias = .{ 2.0, 0.5, 0.9, 0.8 },
        .scale = .{ 0.0, 0.0, 0.0, 0.0 },
        .interpolation_alpha_space = .premultiplied,
    }};

    var lut = try GradientLut(u8).init(allocator, &ranges);
    defer lut.deinit(allocator);

    try testing.expectEqual(@as(usize, 256), lut.width());
    const expected = [4]u8{ 204, 128, 204, 204 };
    for ([_]usize{ 0, 1, 42, 255 }) |idx| {
        try testing.expectEqual(expected, lut.get(idx));
    }

    var f32_lut = try GradientLut(f32).init(allocator, &ranges);
    defer f32_lut.deinit(allocator);
    try testing.expectEqualDeep([4]f32{ 0.8, 0.5, 0.8, 0.8 }, f32_lut.get(0));
    try testing.expectEqualDeep([4]f32{ 0.8, 0.5, 0.8, 0.8 }, f32_lut.get(255));
}

