/// An encoded paint.
pub const EncodedPaint = union(enum) {
    /// An encoded gradient.
    gradient: EncodedGradient,
    /// An encoded image.
    image: EncodedImage,
    /// A blurred, rounded rectangle.
    blurred_rounded_rect: EncodedBlurredRoundedRectangle,

    /// Returns whether this encoded paint may produce non-opaque pixels.
    pub fn mayHaveTransparency(self: EncodedPaint) bool {
        return switch (self) {
            .gradient => |gradient| gradient.may_have_transparency,
            .image => |image| image.may_have_transparency,
            .blurred_rounded_rect => true,
        };
    }

    /// Release the resources owned by this paint.
    pub fn deinit(self: *EncodedPaint, allocator: std.mem.Allocator) void {
        switch (self.*) {
            .gradient => |*gradient| gradient.deinit(allocator),
            .image => |*image| image.deinit(allocator),
            .blurred_rounded_rect => {},
        }
        self.* = undefined;
    }
};

/// Upstream `impl Paint`: whether the paint may produce non-opaque pixels.
///
/// `encoded_paints` must be the list the paint's index refers to.
pub fn paintMayHaveTransparency(paint: Paint, encoded_paints: []const EncodedPaint) bool {
    return switch (paint) {
        .solid => |color| !color.isOpaque(),
        .indexed => |index| encoded_paints[index.index()].mayHaveTransparency(),
    };
}

/// An encoded image.
pub const EncodedImage = struct {
    /// The underlying source of the image.
    source: ImageSource,
    /// Sampling parameters (with `alpha` folded into the tint).
    sampler: ImageSampler,
    /// Whether the image may produce non-opaque pixels.
    may_have_transparency: bool,
    /// The inverse image transform to apply to the first pixel of a span.
    transform: Affine,
    /// The advance in image coordinates for one step in the x direction.
    x_advance: Vec2,
    /// The advance in image coordinates for one step in the y direction.
    y_advance: Vec2,
    /// Optional tint applied to the image.
    tint: ?Tint,

    /// Release the owned image source reference (or pixmap handle).
    pub fn deinit(self: *EncodedImage, allocator: std.mem.Allocator) void {
        self.source.deinit(allocator);
        self.* = undefined;
    }
};

/// Encode an image into `paints` and return its indexed paint.
pub fn encodeImage(
    image: *const Image,
    allocator: std.mem.Allocator,
    paints: *std.ArrayList(EncodedPaint),
    transform: Affine,
    tint: ?Tint,
) Error!Paint {
    const idx = paints.items.len;
    const indexed = try IndexedPaint.new(idx);

    var sampler = image.sampler;
    var encoded_tint = tint;

    // An additional sampler alpha multiplier is folded into the tint's alpha
    // channel so the rasterizer only has to handle a single opacity.
    if (sampler.alpha != 1.0) {
        if (encoded_tint == null) {
            encoded_tint = Tint{ .color = Color.WHITE, .mode = .multiply };
        }
        if (encoded_tint) |*t| {
            const alpha = @min(t.color.components[3] * sampler.alpha, 1.0);
            t.color = t.color.withAlpha(alpha);
        }
        sampler.alpha = 1.0;
    }

    const c = transform.asCoeffs();

    // Optimize image quality for integer-only translations.
    if (math.isNearlyZero(@as(f32, @floatCast(c[0])) - 1.0) and
        math.isNearlyZero(@as(f32, @floatCast(c[1]))) and
        math.isNearlyZero(@as(f32, @floatCast(c[2]))) and
        math.isNearlyZero(@as(f32, @floatCast(c[3])) - 1.0) and
        math.isNearlyZero(@as(f32, @floatCast(c[4] - @floor(c[4])))) and
        math.isNearlyZero(@as(f32, @floatCast(c[5] - @floor(c[5])))) and
        sampler.quality == .medium)
    {
        sampler.quality = .low;
    }

    const encoded_transform = transform.inverse();
    const advances = xYAdvances(encoded_transform);

    // If the tint color has alpha < 1.0, the image will have opacities even if
    // the source pixels are all opaque.
    const has_opacity = if (encoded_tint) |t| t.color.components[3] < 1.0 else false;

    var encoded = EncodedImage{
        .source = image.image.clone(),
        .sampler = sampler,
        .may_have_transparency = image.image.mayHaveTransparency() or has_opacity,
        .transform = encoded_transform,
        .x_advance = advances.x_advance,
        .y_advance = advances.y_advance,
        .tint = encoded_tint,
    };
    errdefer encoded.deinit(allocator);

    try paints.append(allocator, .{ .image = encoded });
    return .{ .indexed = indexed };
}

