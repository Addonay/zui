/// Encode a gradient into `paints` and return its indexed paint.
///
/// Invalid gradients return a solid fallback paint without touching `paints`,
/// exactly like upstream `validate`.
pub fn encodeGradient(
    gradient: *const Gradient,
    allocator: std.mem.Allocator,
    paints: *std.ArrayList(EncodedPaint),
    transform: Affine,
    tint: ?Tint,
) Error!Paint {
    // Upstream ignores the tint for gradients (`_tint`).
    _ = tint;

    if (validate(gradient)) |fallback| return fallback;

    const idx = paints.items.len;
    const indexed = try IndexedPaint.new(idx);

    var may_have_transparency = false;
    for (gradient.stops.items) |stop| {
        if (stop.color.components[3] != 1.0) {
            may_have_transparency = true;
            break;
        }
    }

    // Pad missing first/last offsets to 0/1 so the ranges cover the whole
    // gradient. Ownership: `padded_stops` is a temporary copy released before
    // returning; the original gradient stays borrowed.
    var padded_stops: ?[]ColorStop = null;
    defer if (padded_stops) |padded| allocator.free(padded);
    var stops: []const ColorStop = gradient.stops.items;
    {
        const first = stops[0];
        const last = stops[stops.len - 1];
        if (first.offset != 0.0 or last.offset != 1.0) {
            const pad_first: usize = if (first.offset != 0.0) 1 else 0;
            const pad_last: usize = if (last.offset != 1.0) 1 else 0;
            const padded = try allocator.alloc(ColorStop, stops.len + pad_first + pad_last);
            padded_stops = padded;
            var at: usize = 0;
            if (pad_first == 1) {
                padded[0] = .{ .offset = 0.0, .color = first.color };
                at = 1;
            }
            @memcpy(padded[at..][0..stops.len], stops);
            if (pad_last == 1) {
                padded[at + stops.len] = .{ .offset = 1.0, .color = last.color };
            }
            stops = padded;
        }
    }

    var base_transform: Affine = undefined;
    var kind: EncodedKind = undefined;
    switch (gradient.kind) {
        .linear => |pos| {
            // Map the gradient line to (0, 0) -> (1, 0) so the position along
            // the line is just the interpolated x coordinate.
            base_transform = tsFromLineToLine(pos.start, pos.end, Point.ZERO, Point.new(1.0, 0.0));
            kind = .{ .linear = .{} };
        },
        .radial => |pos| {
            // Translated from Skia's conical gradient implementation:
            // <https://skia.org/docs/dev/design/conical/>
            const c0 = pos.start_center;
            const c1 = pos.end_center;
            const r0 = pos.start_radius;
            const r1 = pos.end_radius;
            const d_radius = r1 - r0;

            const center_distance: f32 = @floatCast(c1.subPoint(c0).length());
            if (math.isNearlyZero(center_distance)) {
                base_transform = Affine.translate(Vec2.new(-c1.x, -c1.y));
                base_transform = base_transform.thenScale(1.0 / @as(f64, @floatCast(@max(r0, r1))));

                const scale = @max(r1, r0) / d_radius;
                const bias = -r0 / d_radius;
                kind = .{ .radial = .{ .radial = .{ .bias = bias, .scale = scale } } };
            } else {
                base_transform = tsFromLineToLine(c0, c1, Point.ZERO, Point.new(1.0, 0.0));

                if (math.isNearlyZero(r1 - r0)) {
                    const scaled_r0 = r1 / center_distance;
                    kind = .{ .radial = .{ .strip = .{
                        .scaled_r0_squared = scaled_r0 * scaled_r0,
                    } } };
                } else {
                    const d_center: f32 = @floatCast(c0.subPoint(c1).length());
                    const focal_data = FocalData.create(r0 / d_center, r1 / d_center, &base_transform);
                    const fp0 = 1.0 / focal_data.fr1;
                    const fp1 = focal_data.f_focal_x;
                    kind = .{ .radial = .{ .focal = .{
                        .focal_data = focal_data,
                        .fp0 = fp0,
                        .fp1 = fp1,
                    } } };
                }
            }
        },
        .sweep => |pos| {
            // Move the center to the origin so the angle is measured from (0, 0).
            const x_offset: f32 = @floatCast(-pos.center.x);
            const y_offset: f32 = @floatCast(-pos.center.y);
            base_transform = Affine.translate(Vec2.new(x_offset, y_offset));

            kind = .{
                .sweep = .{
                    .start_angle = pos.start_angle,
                    // Store the inverse so the renderer can multiply.
                    .inv_angle_delta = 1.0 / (pos.end_angle - pos.start_angle),
                },
            };
        },
    }

    const has_undefined = kind.hasUndefined();
    may_have_transparency = may_have_transparency or has_undefined;

    const ranges = try encodeStops(
        allocator,
        stops,
        gradient.interpolation_cs,
        gradient.hue_direction,
        gradient.interpolation_alpha_space,
    );
    errdefer allocator.free(ranges);

    // Shader base transform followed by the inverse paint transform, so the
    // renderer can start from the first pixel of a span and advance.
    const encoded_transform = base_transform.compose(transform.inverse());
    const advances = xYAdvances(encoded_transform);

    var cache_key = GradientCacheKey{
        .stops = try gradient.stops.clone(allocator),
        .interpolation_cs = gradient.interpolation_cs,
        .hue_direction = gradient.hue_direction,
    };
    errdefer cache_key.stops.deinit();

    const encoded = EncodedGradient{
        .cache_key = cache_key,
        .kind = kind,
        .has_undefined = has_undefined,
        .transform = encoded_transform,
        .x_advance = advances.x_advance,
        .y_advance = advances.y_advance,
        .ranges = ranges,
        .extend = gradient.extend,
        .may_have_transparency = may_have_transparency,
    };

    try paints.append(allocator, .{ .gradient = encoded });
    return .{ .indexed = indexed };
}

/// Returns a fallback paint in case the gradient is invalid: black if there
/// are no stops, otherwise the first stop's color. A `null` result means the
/// gradient is valid.
fn validate(gradient: *const Gradient) ?Paint {
    const black = Paint.fromAlphaColor(peniko.palette.css.BLACK);

    // Gradients need at least two stops.
    if (gradient.stops.items.len == 0) return black;

    const first = Paint.fromAlphaColor(gradient.stops.items[0].color);
    if (gradient.stops.items.len == 1) return first;

    for (gradient.stops.items[0 .. gradient.stops.items.len - 1], gradient.stops.items[1..]) |f, n| {
        // Offsets must be between 0 and 1, and not NaN.
        if (!(f.offset >= 0.0 and f.offset <= 1.0)) return first;
        // Stops must be sorted by ascending offset.
        if (f.offset > n.offset) return first;
    }

    const last = gradient.stops.items[gradient.stops.items.len - 1];
    if (!(last.offset >= 0.0 and last.offset <= 1.0)) return first;

    switch (gradient.kind) {
        .linear => |pos| {
            if (degeneratePoint(pos.start, pos.end)) return first;
        },
        .radial => |pos| {
            // Radii must not be negative.
            if (pos.start_radius < 0.0 or pos.end_radius < 0.0) return first;
            // Radii and center points must not be close to the same.
            if (degeneratePoint(pos.start_center, pos.end_center) and
                degenerateVal(pos.start_radius, pos.end_radius))
            {
                return first;
            }
        },
        .sweep => |pos| {
            // The end angle must be larger than the start angle.
            if (degenerateVal(pos.start_angle, pos.end_angle)) return first;
            if (pos.end_angle <= pos.start_angle) return first;
        },
    }

    return null;
}

fn degeneratePoint(p1: Point, p2: Point) bool {
    return @as(f32, @floatCast(@abs(p1.x - p2.x))) <= DEGENERATE_THRESHOLD and
        @as(f32, @floatCast(@abs(p1.y - p2.y))) <= DEGENERATE_THRESHOLD;
}

fn degenerateVal(v1: f32, v2: f32) bool {
    return @abs(v2 - v1) <= DEGENERATE_THRESHOLD;
}

/// A color stop with its color converted to straight-alpha sRGB (upstream's
/// private `EncodedColorStop`).
const EncodedColorStop = struct {
    offset: f32,
    color: AlphaColor(Srgb),
};

/// Encode all stops into a sequence of ranges.
///
/// The sRGB interpolation path is a direct transcription; see scope decision 1
/// for why other color spaces return `error.Unsupported`.
fn encodeStops(
    allocator: std.mem.Allocator,
    stops: []const ColorStop,
    cs: ColorSpaceTag,
    hue_dir: HueDirection,
    interpolation_alpha_space: InterpolationAlphaSpace,
) Error![]GradientRange {
    _ = hue_dir;

    if (cs != .srgb) return error.Unsupported;

    const ranges = try allocator.alloc(GradientRange, stops.len - 1);
    errdefer allocator.free(ranges);

    for (stops[0 .. stops.len - 1], stops[1..], 0..) |left, right, i| {
        ranges[i] = createRange(
            .{ .offset = left.offset, .color = left.color },
            .{ .offset = right.offset, .color = right.color },
            interpolation_alpha_space,
        );
    }
    return ranges;
}

/// Build a single `GradientRange` between two stops.
fn createRange(
    left_stop: EncodedColorStop,
    right_stop: EncodedColorStop,
    interpolation_alpha_space: InterpolationAlphaSpace,
) GradientRange {
    const x0 = left_stop.offset;
    const x1 = right_stop.offset;

    const c0 = clampColor(if (interpolation_alpha_space == .unpremultiplied)
        left_stop.color.components
    else
        left_stop.color.premultiply().components);
    const c1 = clampColor(if (interpolation_alpha_space == .unpremultiplied)
        right_stop.color.components
    else
        right_stop.color.premultiply().components);

    // Calculate a bias and scale such that `bias + x * scale` interpolates
    // between the two colors. The nudge guards padded stops at equal offsets.
    const x1_minus_x0 = @max(x1 - x0, NUDGE_VAL);
    var scale: [4]f32 = undefined;
    var bias: [4]f32 = undefined;
    for (0..4) |i| {
        scale[i] = (c1[i] - c0[i]) / x1_minus_x0;
        bias[i] = c0[i] - x0 * scale[i];
    }

    return .{
        .x1 = x1,
        .bias = bias,
        .scale = scale,
        .interpolation_alpha_space = interpolation_alpha_space,
    };
}

/// Clamp a color to `[0, 1]`, preserving NaN like Rust's `f32::clamp` (`@min`
/// and `@max` would replace it).
fn clampColor(components: [4]f32) [4]f32 {
    var out = components;
    for (&out) |*c| {
        if (c.* < 0.0) {
            c.* = 0.0;
        } else if (c.* > 1.0) {
            c.* = 1.0;
        }
    }
    return out;
}

/// The transform that maps the first pixel of a span to the next one. See the
/// upstream comment in `encode.rs`: pixels are processed column-major, so the
/// renderer advances by `x_advance`/`y_advance` instead of applying the full
/// transform per pixel.
pub fn xYAdvances(transform: Affine) Advances {
    const c = transform.asCoeffs();
    const scale_skew_transform = Affine.new(.{ c[0], c[1], c[2], c[3], 0.0, 0.0 });

    const x_advance = scale_skew_transform.transformPoint(Point.new(1.0, 0.0));
    const y_advance = scale_skew_transform.transformPoint(Point.new(0.0, 1.0));

    return .{
        .x_advance = Vec2.new(x_advance.x, x_advance.y),
        .y_advance = Vec2.new(y_advance.x, y_advance.y),
    };
}

/// The per-step position deltas returned by [`xYAdvances`].
pub const Advances = struct {
    /// Advance in paint coordinates for one step in the x direction.
    x_advance: Vec2,
    /// Advance in paint coordinates for one step in the y direction.
    y_advance: Vec2,
};

/// Calculate the transform mapping the line spanned by `src1`, `src2` to the
/// line spanned by `dst1`, `dst2`.
///
/// Copied from tiny-skia (via upstream vello_common):
/// <https://github.com/linebender/tiny-skia/blob/68b198a7210a6bbf752b43d6bc4db62445730313/src/shaders/radial_gradient.rs#L182>
fn tsFromLineToLine(src1: Point, src2: Point, dst1: Point, dst2: Point) Affine {
    const unit_to_line1 = unitToLine(src1, src2);
    const line1_to_unit = unit_to_line1.inverse();
    const unit_to_line2 = unitToLine(dst1, dst2);
    return unit_to_line2.compose(line1_to_unit);
}

/// The transform mapping the unit vector to the line spanned by `p0`, `p1`.
fn unitToLine(p0: Point, p1: Point) Affine {
    return Affine.new(.{
        p1.y - p0.y,
        p0.x - p1.x,
        p1.x - p0.x,
        p1.y - p0.y,
        p0.x,
        p0.y,
    });
}

