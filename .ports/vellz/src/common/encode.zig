/// An encoded gradient.
pub const EncodedGradient = struct {
    /// The cache key for the gradient.
    cache_key: GradientCacheKey,
    /// The underlying kind of gradient.
    kind: EncodedKind,
    /// Whether the gradient can yield undefined `t` values at some locations.
    has_undefined: bool,
    /// A transform applied to the position of the first processed pixel.
    transform: Affine,
    /// How much to advance in the x/y direction for one step in the x direction.
    x_advance: Vec2,
    /// How much to advance in the x/y direction for one step in the y direction.
    y_advance: Vec2,
    /// The color ranges of the gradient.
    ranges: []GradientRange,
    /// The extend mode of the gradient.
    extend: Extend,
    /// Whether the gradient requires `source_over` compositing.
    may_have_transparency: bool,
    /// Lazily built u8 LUT (upstream `OnceCell<GradientLut<u8>>`).
    u8_lut: ?GradientLut(u8) = null,
    /// Lazily built f32 LUT (upstream `OnceCell<GradientLut<f32>>`).
    f32_lut: ?GradientLut(f32) = null,

    /// Get the lookup table for sampling u8-based gradient values, building it
    /// on first access.
    ///
    /// Divergence: upstream's `OnceCell::get_or_init` takes `&self` and panics
    /// on allocation failure; this port takes `*EncodedGradient` (single
    /// threaded; M4 adds synchronization) and propagates `error.OutOfMemory`.
    pub fn u8Lut(self: *EncodedGradient, allocator: std.mem.Allocator) std.mem.Allocator.Error!*const GradientLut(u8) {
        if (self.u8_lut == null) {
            self.u8_lut = try GradientLut(u8).init(allocator, self.ranges);
        }
        if (self.u8_lut) |*lut| return lut;
        unreachable;
    }

    /// Get the lookup table for sampling f32-based gradient values, building
    /// it on first access. See [`EncodedGradient.u8Lut`].
    pub fn f32Lut(self: *EncodedGradient, allocator: std.mem.Allocator) std.mem.Allocator.Error!*const GradientLut(f32) {
        if (self.f32_lut == null) {
            self.f32_lut = try GradientLut(f32).init(allocator, self.ranges);
        }
        if (self.f32_lut) |*lut| return lut;
        unreachable;
    }

    /// Release the range/stops allocations and any built LUTs.
    pub fn deinit(self: *EncodedGradient, allocator: std.mem.Allocator) void {
        self.cache_key.stops.deinit();
        allocator.free(self.ranges);
        if (self.u8_lut) |*lut| lut.deinit(allocator);
        if (self.f32_lut) |*lut| lut.deinit(allocator);
        self.* = undefined;
    }
};

/// Cache key for gradient color ramps based on color-affecting properties.
pub const GradientCacheKey = struct {
    /// The color stops (offsets + colors).
    stops: ColorStops,
    /// Color space used for interpolation.
    interpolation_cs: ColorSpaceTag,
    /// Hue direction used for interpolation.
    hue_direction: HueDirection,

    /// Release the owned stops copy.
    pub fn deinit(self: *GradientCacheKey) void {
        self.stops.deinit();
    }

    /// Upstream `BitEq`: compare the stops and enum tags bit-for-bit (NaN
    /// offsets/colors compare equal when their bit patterns match).
    pub fn bitEql(self: *const GradientCacheKey, other: *const GradientCacheKey) bool {
        if (self.interpolation_cs != other.interpolation_cs) return false;
        if (self.hue_direction != other.hue_direction) return false;
        if (self.stops.items.len != other.stops.items.len) return false;
        for (self.stops.items, other.stops.items) |a, b| {
            if (!f32BitEql(a.offset, b.offset)) return false;
            for (a.color.components, b.color.components) |x, y| {
                if (!f32BitEql(x, y)) return false;
            }
        }
        return true;
    }

    /// Upstream `BitHash`: hash the stop bit patterns and the enum tags.
    ///
    /// The byte format is not part of the rendering contract yet; it only
    /// needs to be stable and consistent with [`GradientCacheKey.bitEql`]
    /// once a gradient cache consumes it.
    pub fn hash(self: *const GradientCacheKey, hasher: anytype) void {
        const len: u64 = self.stops.items.len;
        hasher.update(std.mem.asBytes(&len));
        for (self.stops.items) |stop| {
            const offset_bits: u32 = @bitCast(stop.offset);
            hasher.update(std.mem.asBytes(&offset_bits));
            for (stop.color.components) |component| {
                const bits: u32 = @bitCast(component);
                hasher.update(std.mem.asBytes(&bits));
            }
        }
        const cs = self.interpolation_cs.toU8();
        hasher.update(std.mem.asBytes(&cs));
        const hue = self.hue_direction.toU8();
        hasher.update(std.mem.asBytes(&hue));
    }
};

fn f32BitEql(a: f32, b: f32) bool {
    return @as(u32, @bitCast(a)) == @as(u32, @bitCast(b));
}

/// An encoded range between two color stops.
pub const GradientRange = struct {
    /// The end value of the range.
    x1: f32,
    /// The bias to apply when interpolating the color (the start color).
    bias: [4]f32,
    /// The scale factors of the range: `bias + x * scale`.
    scale: [4]f32,
    /// The alpha space in which the interpolation was performed.
    interpolation_alpha_space: InterpolationAlphaSpace,
};

