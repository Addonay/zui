/// Computed properties of a linear gradient (upstream `LinearKind`).
pub const LinearKind = struct {};

/// Focal data for a two-point radial gradient.
pub const FocalData = struct {
    /// The normalized radius of the outer circle in focal space.
    fr1: f32,
    /// The x-coordinate of the focal point in normalized space.
    f_focal_x: f32,
    /// Whether the focal points have been swapped.
    f_is_swapped: bool,

    /// Create new focal data with the given radii and update `matrix`.
    pub fn create(r0_in: f32, r1_in: f32, matrix: *Affine) FocalData {
        var r0 = r0_in;
        var r1 = r1_in;
        var swapped = false;
        var f_focal_x = r0 / (r0 - r1);

        if (math.isNearlyZero(f_focal_x - 1.0)) {
            matrix.* = matrix.thenTranslate(Vec2.new(-1.0, 0.0));
            matrix.* = matrix.thenScaleNonUniform(-1.0, 1.0);
            std.mem.swap(f32, &r0, &r1);
            f_focal_x = 0.0;
            swapped = true;
        }

        const focal_matrix = tsFromLineToLine(
            Point.new(f_focal_x, 0.0),
            Point.new(1.0, 0.0),
            Point.new(0.0, 0.0),
            Point.new(1.0, 0.0),
        );
        matrix.* = focal_matrix.compose(matrix.*);

        const fr1 = r1 / @abs(1.0 - f_focal_x);

        const data = FocalData{
            .fr1 = fr1,
            .f_focal_x = f_focal_x,
            .f_is_swapped = swapped,
        };

        if (data.isFocalOnCircle()) {
            matrix.* = matrix.thenScale(0.5);
        } else {
            matrix.* = matrix.thenScaleNonUniform(
                @as(f64, fr1 / (fr1 * fr1 - 1.0)),
                1.0 / @as(f64, @sqrt(@abs(fr1 * fr1 - 1.0))),
            );
        }

        matrix.* = matrix.thenScale(@as(f64, @abs(1.0 - f_focal_x)));

        return data;
    }

    /// Whether the focal is on the circle.
    pub fn isFocalOnCircle(self: FocalData) bool {
        return math.isNearlyZero(1.0 - self.fr1);
    }

    /// Whether the focal points have been swapped.
    pub fn isSwapped(self: FocalData) bool {
        return self.f_is_swapped;
    }

    /// Whether the gradient is well-behaved.
    pub fn isWellBehaved(self: FocalData) bool {
        return !self.isFocalOnCircle() and self.fr1 > 1.0;
    }

    /// Whether the gradient is natively focal.
    pub fn isNativelyFocal(self: FocalData) bool {
        return math.isNearlyZero(self.f_focal_x);
    }
};

/// A radial gradient kind.
pub const RadialKind = union(enum) {
    /// The start and end center points are the same.
    radial: Radial,
    /// The start and end radius are the same.
