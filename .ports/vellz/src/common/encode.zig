/// Zig face of upstream's `EncodeExt` trait: callers dispatch on the paint
/// type at compile time. `Gradient`, `Image`, and `BlurredRoundedRectangle`
/// are accepted by value or by pointer; passing by value is a shallow borrow
/// (the encoder clones what it stores and never frees the input).
pub const EncodeExt = struct {
    pub const encodeInto = dispatchEncode;
};

/// Encode `value` and append the encoded paint to `paints`, returning the
/// corresponding indexed (or fallback solid) `Paint`.
pub fn encodeInto(
    value: anytype,
    allocator: std.mem.Allocator,
    paints: *std.ArrayList(EncodedPaint),
    transform: Affine,
    tint: ?Tint,
) Error!Paint {
    return dispatchEncode(value, allocator, paints, transform, tint);
}

fn dispatchEncode(
    value: anytype,
    allocator: std.mem.Allocator,
    paints: *std.ArrayList(EncodedPaint),
    transform: Affine,
    tint: ?Tint,
) Error!Paint {
    const V = @TypeOf(value);
    if (V == Gradient or V == *const Gradient or V == *Gradient) {
        const gradient: *const Gradient = if (@typeInfo(V) == .pointer) value else &value;
        return encodeGradient(gradient, allocator, paints, transform, tint);
    }
    if (V == Image or V == *const Image or V == *Image) {
        const image: *const Image = if (@typeInfo(V) == .pointer) value else &value;
        return encodeImage(image, allocator, paints, transform, tint);
    }
    if (V == BlurredRoundedRectangle or V == *const BlurredRoundedRectangle or V == *BlurredRoundedRectangle) {
        const rect: *const BlurredRoundedRectangle = if (@typeInfo(V) == .pointer) value else &value;
        return encodeBlurredRoundedRectangle(rect, allocator, paints, transform, tint);
    }
    @compileError("EncodeExt.encodeInto: unsupported paint type " ++ @typeName(V));
}

